    // --------------------------------------------------
    // getGlyph(c)
    // Returns pointer to 6-byte bitmap in flash,
    // or nullptr if c is outside the supported range.
    // --------------------------------------------------
    inline const uint8_t* getGlyph(char c)
    {
        uint8_t idx = (uint8_t)c;
        if (idx < 0x20 || idx > 0x7E)
            return nullptr;
        return _table[idx - 0x20];
    }
